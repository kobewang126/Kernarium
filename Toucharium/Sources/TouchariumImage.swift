import CryptoKit
import Foundation

nonisolated struct TouchariumImageDescriptor: Codable, Sendable, Equatable {
    let filename: String
    let size: Int64
    let sha256: String
    let policyVersion: Int

    static func validFilename(_ value: String) -> Bool {
        !value.isEmpty && value.utf8.count <= 255 && !value.hasPrefix(".")
            && value == (value as NSString).lastPathComponent
            && !value.contains("\\") && !value.contains(":")
            && !value.unicodeScalars.contains(where: { $0.value < 32 || $0.value == 127 })
            && value.lowercased().hasSuffix(".erofs")
    }

    func validated() throws -> Self {
        let checksum = sha256.lowercased()
        guard policyVersion == 2, size >= 4096, size <= Int64.max - (128 << 20),
              Self.validFilename(filename), checksum.utf8.count == 64,
              checksum.utf8.allSatisfy({ (48...57).contains($0) || (97...102).contains($0) }) else {
            throw TouchariumImageError.invalidDescriptor
        }
        return Self(filename: filename, size: size, sha256: checksum, policyVersion: policyVersion)
    }

    static func load(from url: URL) throws -> Self {
        let access = url.startAccessingSecurityScopedResource()
        defer { if access { url.stopAccessingSecurityScopedResource() } }
        guard url.isFileURL, url.lastPathComponent.lowercased().hasSuffix(".import.json"),
              try url.resourceValues(forKeys: [.isRegularFileKey]).isRegularFile == true else {
            throw TouchariumImageError.invalidDescriptor
        }
        let input = try FileHandle(forReadingFrom: url)
        defer { try? input.close() }
        guard let data = try input.read(upToCount: 65537), !data.isEmpty, data.count <= 65536 else {
            throw TouchariumImageError.invalidDescriptor
        }
        return try JSONDecoder().decode(Self.self, from: data).validated()
    }
}

nonisolated enum TouchariumImageError: LocalizedError {
    case invalidSelection, invalidDescriptor, unsupportedFormat, unsupportedImage, insufficientSpace

    var errorDescription: String? {
        switch self {
        case .invalidSelection: "Select one .erofs image and its matching .import.json file."
        case .invalidDescriptor: "Choose a valid .import.json file generated by the Toucharium packaging tool."
        case .unsupportedFormat: "This image format is not supported. Choose the .erofs file produced by the packaging tool."
        case .unsupportedImage: "The image does not match its import file. Check that both files belong together."
        case .insufficientSpace: "There is not enough free storage to import this system image."
        }
    }
}

nonisolated enum TouchariumImage {
    static let installedFilename = "TouchariumSystem.erofs"

    struct Installation {
        let descriptor: TouchariumImageDescriptor
        let filename: String
    }

    private struct Receipt: Codable {
        let sha256: String
        let size: Int64
        let modified: Date
        let descriptor: TouchariumImageDescriptor?
        let storageFilename: String?
    }

    static func receiptURL(in directory: URL) -> URL {
        directory.appendingPathComponent("UbuntuTouch/imported-image.json")
    }

    static func removeInterruptedImports(in directory: URL) throws {
        let manager = FileManager.default
        guard manager.fileExists(atPath: directory.path) else { return }
        for url in try manager.contentsOfDirectory(at: directory, includingPropertiesForKeys: [.isRegularFileKey]) {
            let prefix = ".toucharium-import-"
            guard url.lastPathComponent.hasPrefix(prefix),
                  UUID(uuidString: String(url.lastPathComponent.dropFirst(prefix.count))) != nil,
                  try url.resourceValues(forKeys: [.isRegularFileKey]).isRegularFile == true else { continue }
            try manager.removeItem(at: url)
        }
    }

    static func installation(in directory: URL, legacyFilename: String? = nil) -> Installation? {
        guard let data = try? Data(contentsOf: receiptURL(in: directory)),
              let receipt = try? JSONDecoder().decode(Receipt.self, from: data),
              let filename = receipt.storageFilename ?? legacyFilename,
              TouchariumImageDescriptor.validFilename(filename) else { return nil }
        // Earlier installations recorded the digest and metadata after a full
        // verification; their storage name remains in the launch preferences.
        let candidate = receipt.descriptor ?? TouchariumImageDescriptor(
            filename: filename, size: receipt.size, sha256: receipt.sha256, policyVersion: 2)
        let image = directory.appendingPathComponent(filename)
        guard let descriptor = try? candidate.validated(),
              let values = try? image.resourceValues(forKeys:
                [.fileSizeKey, .contentModificationDateKey, .isRegularFileKey, .isSymbolicLinkKey]),
              values.isRegularFile == true, values.isSymbolicLink != true,
              receipt.sha256 == descriptor.sha256, receipt.size == descriptor.size,
              Int64(values.fileSize ?? 0) == descriptor.size,
              values.contentModificationDate == receipt.modified else { return nil }
        return Installation(descriptor: descriptor, filename: filename)
    }

    static func isInstalled(_ descriptor: TouchariumImageDescriptor, in directory: URL) -> Bool {
        guard let descriptor = try? descriptor.validated() else { return false }
        return installation(in: directory, legacyFilename: descriptor.filename)?.descriptor == descriptor
    }

    /// A failed, cancelled or mismatched import never publishes the staging file.
    static func install(
        from source: URL, descriptor: TouchariumImageDescriptor, into directory: URL,
        progress: @Sendable (Double) -> Void = { _ in }
    ) throws -> URL {
        let descriptor = try descriptor.validated()
        let access = source.startAccessingSecurityScopedResource()
        defer { if access { source.stopAccessingSecurityScopedResource() } }
        let values = try source.resourceValues(forKeys: [.fileSizeKey, .isRegularFileKey])
        guard source.pathExtension.lowercased() == "erofs", values.isRegularFile == true,
              Int64(values.fileSize ?? 0) == descriptor.size else {
            throw TouchariumImageError.unsupportedImage
        }
        let manager = FileManager.default
        try manager.createDirectory(at: directory, withIntermediateDirectories: true)
        let space = try manager.attributesOfFileSystem(forPath: directory.path)
        if let free = space[.systemFreeSize] as? NSNumber,
           free.int64Value < descriptor.size + (128 << 20) {
            throw TouchariumImageError.insufficientSpace
        }
        let staging = directory.appendingPathComponent(".toucharium-import-\(UUID().uuidString)")
        guard manager.createFile(atPath: staging.path, contents: nil) else {
            throw CocoaError(.fileWriteUnknown)
        }
        defer { try? manager.removeItem(at: staging) }
        let input = try FileHandle(forReadingFrom: source)
        defer { try? input.close() }
        try input.seek(toOffset: 1024)
        guard let header = try input.read(upToCount: 13), header.count == 13,
              header.prefix(4) == Data([0xe2, 0xe1, 0xf5, 0xe0]), header[12] == 12 else {
            throw TouchariumImageError.unsupportedFormat
        }
        try input.seek(toOffset: 0)
        let output = try FileHandle(forWritingTo: staging)
        defer { try? output.close() }
        var hasher = SHA256()
        var total: Int64 = 0
        while let block = try input.read(upToCount: 4 << 20), !block.isEmpty {
            try Task.checkCancellation()
            total += Int64(block.count)
            guard total <= descriptor.size else { throw TouchariumImageError.unsupportedImage }
            hasher.update(data: block)
            try output.write(contentsOf: block)
            progress(Double(total) / Double(descriptor.size))
        }
        let checksum = hasher.finalize().map { String(format: "%02x", $0) }.joined()
        guard total == descriptor.size, checksum == descriptor.sha256 else {
            throw TouchariumImageError.unsupportedImage
        }
        try Task.checkCancellation()
        try output.synchronize()
        try output.close()
        let destination = directory.appendingPathComponent(installedFilename)
        if manager.fileExists(atPath: destination.path) {
            let existing = try destination.resourceValues(forKeys: [.isRegularFileKey, .isSymbolicLinkKey])
            guard existing.isRegularFile == true, existing.isSymbolicLink != true else {
                throw TouchariumImageError.unsupportedImage
            }
            _ = try manager.replaceItemAt(destination, withItemAt: staging)
        } else {
            try manager.moveItem(at: staging, to: destination)
        }
        var image = destination
        var resource = URLResourceValues()
        resource.isExcludedFromBackup = true
        try image.setResourceValues(resource)
        let installed = try image.resourceValues(forKeys: [.contentModificationDateKey])
        guard let modified = installed.contentModificationDate else { throw CocoaError(.fileReadUnknown) }
        let receipt = Receipt(sha256: checksum, size: total, modified: modified,
                              descriptor: descriptor, storageFilename: installedFilename)
        let url = receiptURL(in: directory)
        try manager.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try JSONEncoder().encode(receipt).write(to: url, options: .atomic)
        return destination
    }
}
